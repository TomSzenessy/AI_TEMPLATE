"""Portable session lifecycle: what happens at start, before compaction, after an
edit, and before an agent declares it is done.

Hosts with hooks call `repoctl hook <event>` (Claude Code via the generated
`.claude/settings.json`); hosts without hooks run `make start` and
`make finish`. Every event reads optional host JSON on stdin and never needs it.
Output is evidence about the repository, not new authority: AGENTS.md rules.
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

from . import adapters, docsync, hygiene
from .core import RepoctlError, governance_profile, load_project, read_text_file, repository_files
from .garden import self_heal_errors
from .gitinfo import branch, branch_paths, changed_paths, git, head
from .navigate import print_map
from .risk import assess

HANDOVER_LIMIT = 4000
CHECKPOINT = ".agent/checkpoint.md"
MAP_LIMIT = 15
STATE = ".agent/hook-state.json"
CANONICAL_INPUTS = (".agents/skills/", ".agents/agents/", "resources.toml", "project.toml")


def read_event() -> dict[str, object]:
    if sys.stdin is None or sys.stdin.isatty():
        return {}
    try:
        data = json.loads(sys.stdin.read() or "{}")
    except (json.JSONDecodeError, OSError, UnicodeDecodeError):
        return {}
    return data if isinstance(data, dict) else {}


def _relative(root: Path, value: object) -> str | None:
    if not isinstance(value, str) or not value:
        return None
    path = Path(value)
    try:
        return (path if path.is_absolute() else root / path).resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return None


def _heal_adapters(root: Path) -> list[str]:
    try:
        return adapters.sync(root)
    except (RepoctlError, OSError) as error:
        return [f"adapter regeneration failed: {error}"]


def session_start(root: Path) -> None:
    project = load_project(root)
    changed = changed_paths(root)
    print("# Session brief (generated by `repoctl hook session-start`; repository facts, AGENTS.md rules)")
    print(
        f"{project.get('name')} · phase={project.get('phase')} · profile={governance_profile(project)} · "
        f"branch {branch(root)} @ {head(root)} · {len(changed)} uncommitted path(s)"
    )
    recent = (git(root, "log", "-5", "--format=- %h %s") or "").strip()
    if recent:
        print("\nRecent commits:\n" + recent)
    handover = read_text_file(root, "HANDOVER.md")
    if handover:
        clipped = handover[:HANDOVER_LIMIT] + ("\n… (truncated; read HANDOVER.md)" if len(handover) > HANDOVER_LIMIT else "")
        print("\n## HANDOVER.md (read first; verify against the working tree)\n" + clipped)
    if (root / CHECKPOINT).is_file():
        print(f"\nPre-compaction checkpoint available: {CHECKPOINT}")
    healed = _heal_adapters(root)
    print()
    print_map(root, limit=MAP_LIMIT)
    try:
        findings = self_heal_errors(root, project)
    except (RepoctlError, OSError) as error:
        findings = [str(error)]
    if healed:
        findings.insert(0, "regenerated host adapters: " + ", ".join(healed))
    print("\n## Needs attention")
    print("\n".join(f"- {item}" for item in findings[:15]) or "- nothing: the self-healing checks are green")
    print(
        "\n## Working agreement\n"
        "- You orchestrate and keep the goal; delegate bounded searches, builds, reviews, and doc fixes to the roles\n"
        "  in .agents/agents/ using the brief in docs/delegation.md. Subagent reports must stay short and cite file:line.\n"
        "- Navigate with `make where Q=\"...\"` before broad searching; `make risk` sets the ceremony for your change.\n"
        "- Before declaring done: update the docs that cover what you changed, then `make finish` and `make verify`."
    )


def pre_compact(root: Path) -> None:
    changed = changed_paths(root)
    doc_bindings = docsync.bindings(root, repository_files(root))
    pending = docsync.pending_documents(doc_bindings, changed)
    lines = [
        "# Pre-compaction checkpoint",
        "",
        f"Written: {datetime.now(timezone.utc).isoformat(timespec='seconds')} on branch {branch(root)} @ {head(root)}.",
        "Compare with `git status`; update HANDOVER.md with goal, decisions, and next action if the work continues.",
        "",
        "## Uncommitted paths",
        *(f"- {path}" for path in changed[:60]),
        "",
        "## Documents that still need updating",
        *([f"- {doc} (covers {', '.join(paths[:5])})" for doc, paths in pending.items()] or ["- none"]),
    ]
    target = root / CHECKPOINT
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"checkpoint written to {CHECKPOINT}")


def _load_state(root: Path, session: str) -> dict[str, list[str]]:
    try:
        state = json.loads((root / STATE).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        state = {}
    return state if isinstance(state, dict) and state.get("session") == session else {"session": session, "noted": []}


def after_edit(root: Path, event: dict[str, object]) -> None:
    tool_input = event.get("tool_input") if isinstance(event.get("tool_input"), dict) else {}
    relative = _relative(root, tool_input.get("file_path") or tool_input.get("notebook_path"))
    if not relative:
        return
    notes = []
    if relative.startswith(".claude/") or relative == ".mcp.json":
        notes.append(f"{relative} is generated. Put the change in .agents/ or resources.toml; `make adapters` regenerates it.")
    elif relative.startswith(CANONICAL_INPUTS):
        healed = _heal_adapters(root)
        if healed:
            notes.append("Host adapters regenerated from the canonical source: " + ", ".join(healed))
    session = str(event.get("session_id", "local"))
    state = _load_state(root, session)
    owned = [doc for doc in docsync.owners(docsync.bindings(root, repository_files(root)), relative) if doc not in state["noted"]]
    if owned:
        notes.append(f"{relative} is documented by {', '.join(owned)}; keep it true in this change (the stop gate checks).")
        state["noted"] = sorted(set(state["noted"]) | set(owned))
        (root / STATE).parent.mkdir(parents=True, exist_ok=True)
        (root / STATE).write_text(json.dumps(state), encoding="utf-8")
    if notes:
        print(json.dumps({"hookSpecificOutput": {"hookEventName": "PostToolUse", "additionalContext": " ".join(notes)}}))


def finish_findings(root: Path) -> list[str]:
    """Fast completion gate over this branch's change set (commits since the base plus uncommitted)."""
    repository = load_project(root).get("repository", {})
    base = str(repository.get("default_branch", "main")) if isinstance(repository, dict) else "main"
    changed = branch_paths(root, base)
    if not changed:
        return []
    files = repository_files(root)
    doc_bindings = docsync.bindings(root, files)
    findings = [
        f"{doc} covers changed {', '.join(paths[:4])}{' …' if len(paths) > 4 else ''} but was not updated"
        " (update it, or record why in the commit with a 'Docs-Unaffected: <doc> <reason>' trailer)"
        for doc, paths in docsync.pending_documents(doc_bindings, changed).items()
    ]
    findings += adapters.drift(root)
    findings += docsync.dead_bindings(doc_bindings, files)
    present = [path for path in changed if path in set(files)]
    findings += hygiene.scan_markers(root, present).errors
    return findings


def stop(root: Path, event: dict[str, object]) -> None:
    if event.get("stop_hook_active"):
        return  # the agent already continued once because of this gate
    findings = finish_findings(root)
    if findings:
        reason = "Self-healing gate before stopping:\n" + "\n".join(f"- {item}" for item in findings[:12])
        reason += "\nFix these (delegate doc work to the doc-gardener role if large), or explain to the user why they stay."
        print(json.dumps({"decision": "block", "reason": reason}))


def finish(root: Path) -> int:
    findings = finish_findings(root)
    tier, _ = assess(root)
    print(f"Change risk tier: {tier} (details: make risk)")
    if findings:
        print("Not finished:\n" + "\n".join(f"- {item}" for item in findings))
        return 1
    print("Self-healing gate passed for this branch's change set. Next: make verify, critic review per tier, handover if work continues.")
    return 0


def run_hook(root: Path, event_name: str) -> int:
    event = read_event()
    handlers = {
        "session-start": lambda: session_start(root),
        "pre-compact": lambda: pre_compact(root),
        "after-edit": lambda: after_edit(root, event),
        "stop": lambda: stop(root, event),
    }
    try:
        handlers[event_name]()
    except (RepoctlError, OSError) as error:
        # A hook must never wedge the host session; report and continue.
        print(f"repoctl hook {event_name}: {error}", file=sys.stderr)
    return 0
